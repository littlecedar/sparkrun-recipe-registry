#!/usr/bin/env python3
"""Aggregate EVERY benchmark result in results/ into one comparison.

Scans all `results/<model>.<bench>.<thinking>[.<tag>].json` files produced by the
three harnesses (`run_benchmarks.py`, `bench_reason.py`, `bench_code.py`) and
builds one matrix, with the published reference score beside each row.

The headline analysis is **paired**: both models answer the *same* items, so the
right test is not "are the two percentages different" but "of the items where the
two disagree, is the split lopsided?"  For each bench this computes the discordant
pairs (only-A-correct, only-B-correct) and an exact two-sided binomial p-value on
them (McNemar's test without continuity correction) -- the honest way to say
whether a 1-4 pp gap is signal or coin-flip.  Ties are flagged as such.

Emits `results/RESULTS.md` and `results/summary_all.json`.
"""
from __future__ import annotations

import glob
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")

MODEL_LABEL = {"deepseek": "`deepseek` (official)", "deepseek-turbo": "`deepseek-turbo` (EXL3 2.9bpw)"}

# bench -> (label, metric, published reference for the UNQUANTISED model)
BENCH_META = {
    "house":     ("House battery (37)", "accuracy", "—"),
    "gsm8k":     ("GSM8K (0-shot)", "EM", "93.0 (base, 8-shot)"),
    "arc":       ("ARC-Challenge (0-shot)", "accuracy", "—"),
    "hle":       ("HLE text-only", "Pass@1", "36.8 / 39.1 text-only"),
    "gpqa":      ("GPQA Diamond", "Pass@1", "90.9"),
    "mmlu_pro":  ("MMLU-Pro", "EM", "74.1 (base, 5-shot)"),
    "math500":   ("MATH-500", "EM", "not published (MATH 61.1 base)"),
    "aime":      ("AIME 2022-24", "accuracy", "AIME 2026 100 (max effort)"),
    "humaneval": ("HumanEval (exec-graded)", "Pass@1", "79.4 (base, 0-shot)"),
    "mbpp":      ("MBPP (exec-graded)", "Pass@1", "not published"),
}
ORDER = ["house", "gsm8k", "arc", "hle", "gpqa", "mmlu_pro", "math500", "aime", "humaneval", "mbpp"]


def discover():
    out = {}
    for path in sorted(glob.glob(os.path.join(RESULTS, "*.json"))):
        name = os.path.basename(path)[:-5]
        if name.startswith("summary") or name == "RESULTS":
            continue
        parts = name.split(".")
        if len(parts) < 3:
            continue
        model, bench, thinking = parts[0], parts[1], parts[2]
        tag = ".".join(parts[3:]) if len(parts) > 3 else ""
        try:
            out[(model, bench, thinking, tag)] = json.load(open(path))
        except Exception:  # noqa: BLE001
            pass
    return out


def binom_two_sided(k, n, p=0.5):
    """Exact two-sided binomial p-value for k successes in n trials."""
    if n == 0:
        return 1.0
    def pmf(i):
        return math.comb(n, i) * p ** i * (1 - p) ** (n - i)
    obs = pmf(k)
    return min(1.0, sum(pmf(i) for i in range(n + 1) if pmf(i) <= obs + 1e-12))


def paired(a_items, b_items):
    """Return (both, a_only, b_only, only_a_ids, only_b_ids) over shared ids."""
    A = {r["id"]: r["correct"] for r in a_items}
    B = {r["id"]: r["correct"] for r in b_items}
    shared = sorted(set(A) & set(B))
    both = a_only = b_only = 0
    oa, ob = [], []
    for i in shared:
        if A[i] and B[i]:
            both += 1
        elif A[i] and not B[i]:
            a_only += 1
            oa.append(i)
        elif B[i] and not A[i]:
            b_only += 1
            ob.append(i)
    return len(shared), both, a_only, b_only, oa, ob


def main():
    d = discover()
    models = sorted({k[0] for k in d})
    ma, mb = models[0], models[1]
    summary = {"models": models, "cells": {}, "paired": {}}

    lines = ["# ds4 hard benchmark battery — results", "",
             "Generated by `compare_all.py`. `deepseek` = official weights (SGLang); "
             "`deepseek-turbo` = EXL3 2.9 bpw (TensorFold). All runs greedy "
             "(`temperature=0`), **thinking off** for the primary table (the only "
             "config that yields graded answers on HLE-class prompts; see README).", "",
             "## Primary — thinking off", "",
             "| Benchmark | Metric | `deepseek` | `deepseek-turbo` | Δ | discordant (ds-only / turbo-only) | McNemar p | verdict | published (unq.) |",
             "|:--|:--|--:|--:|--:|:--:|--:|:--|:--|"]

    for b in ORDER:
        ra, rb = d.get((ma, b, "off", "")), d.get((mb, b, "off", ""))
        if not ra or not rb:
            continue
        la, la_metric, ref = BENCH_META[b]
        n, both, ao, bo, oa, ob = paired(ra["items"], rb["items"])
        disc = ao + bo
        p = binom_two_sided(min(ao, bo), disc)
        verdict = "tie" if p >= 0.05 else ("turbo +" if bo > ao else "ds +")
        delta = rb["pct"] - ra["pct"]
        summary["cells"][b] = {"ds": ra["pct"], "turbo": rb["pct"], "n": n,
                               "ds_only": ao, "turbo_only": bo, "mcnemar_p": p}
        lines.append(
            f"| {la} | {la_metric} | {ra['correct']}/{ra['n']} = {ra['pct']:.1f}% | "
            f"{rb['correct']}/{rb['n']} = {rb['pct']:.1f}% | {delta:+.1f} pp | "
            f"{ao} / {bo} (n={disc}) | {p:.2f} | {verdict} | {ref} |")

    # secondary arms
    rows = {}
    for (model, bench, thinking, tag), v in d.items():
        if thinking == "on" or tag:
            label = BENCH_META.get(bench, (bench,))[0] + f" — {thinking}" + (f".{tag}" if tag else "")
            rows.setdefault(label, {})[model] = f"{v['correct']}/{v['n']} = {v['pct']:.1f}%"
    if rows:
        lines += ["", "## Secondary arms (thinking on, repeats, diagnostics)", "",
                  "| Arm | " + " | ".join(MODEL_LABEL.get(m, m) for m in models) + " |",
                  "|:--|" + "--:|" * len(models)]
        for label in sorted(rows):
            lines.append(f"| {label} | " + " | ".join(rows[label].get(m, "—") for m in models) + " |")

    lines += ["", "## How to read 'verdict' and 'McNemar p'", "",
              "`discordant` counts the items the two models disagreed on. If a gap were "
              "real, those disagreements would be lopsided; `McNemar p` is the exact "
              "two-sided probability of the observed (or more lopsided) split under a "
              "fair coin. `p >= 0.05` → **tie** (the gap is consistent with noise). "
              "Small `n` and near-ceiling benchmarks (ARC, HumanEval, MATH-500) have "
              "very few discordant items, so only a large, consistent gap could ever "
              "reach significance here.", ""]

    txt = "\n".join(lines) + "\n"
    open(os.path.join(RESULTS, "RESULTS.md"), "w").write(txt)
    summary["paired"] = {b: v for b, v in summary["cells"].items()}
    json.dump(summary, open(os.path.join(RESULTS, "summary_all.json"), "w"), indent=1)
    print(txt)


if __name__ == "__main__":
    main()